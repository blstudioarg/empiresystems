<p>Acá ves el <strong>embudo comercial</strong> (leads → oportunidades → presupuestos → negocio
cerrado) convertido en indicadores y ratios de eficiencia para el periodo que elijas.</p>

<ol>
	<li><strong>Periodo</strong>: mes, trimestre, año en curso o un rango personalizado, igual que
		en el dashboard financiero.</li>
	<li><strong>Filtros</strong>: por canal de captación y, si tenés permiso de "Informes de todo
		el equipo", por comercial asignado. Los filtros se mantienen al cambiar de periodo.</li>
	<li><strong>Criterio de fecha</strong>: cada indicador lleva una etiqueta (Cohorte / Evento /
		Instantánea) que indica qué fecha usa para ubicarse en el periodo — así las cifras son
		auditables y comparables.</li>
	<li><strong>Comparativa</strong>: activá "Comparar con el ejercicio anterior" para ver, junto a
		cada indicador, el valor del mismo periodo del año pasado y la variación.</li>
	<li><strong>Exportar</strong>: descarga un Excel con el mismo periodo, filtros e indicadores que
		estás viendo en pantalla.</li>
</ol>

<p class="ayuda-nota">Si no tenés el permiso "Informes de todo el equipo", solo ves tu propia
	actividad asignada, y el negocio cerrado del embudo solo cuenta facturas originadas en un
	presupuesto (nunca altas directas ni ventas de punto de venta).</p>
