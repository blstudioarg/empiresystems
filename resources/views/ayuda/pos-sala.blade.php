<p>La sala muestra todas las mesas del local y en qué estado está cada una. Es la pantalla desde
la que se abren, se retoman y se cobran las cuentas.</p>

<ol>
	<li><strong>Elegir cómo verla</strong>: arriba a la derecha se cambia entre
		<em>Tarjetas</em> (la rejilla de siempre) y <em>Plano</em> (las mesas dibujadas donde están
		de verdad en el local). La elección se recuerda para la próxima vez que entres, en ese
		dispositivo y para tu usuario.</li>
	<li><strong>Filtrar por zona</strong>: las pestañas de arriba filtran las mesas. «Todas» muestra
		el local entero. En la vista de plano, «Todas» no aplica —el plano es de una zona— y aparece
		deshabilitada: se muestra la primera zona.</li>
	<li><strong>Abrir una cuenta</strong>: tocá una mesa <em>libre</em> (borde gris) y se abre el
		TPV con esa mesa ya seleccionada. La cuenta se crea al guardar la primera línea, así que
		tocar una mesa por error no deja nada abierto.</li>
	<li><strong>Retomar una cuenta</strong>: tocá una mesa <em>ocupada</em> (borde verde) para
		volver a su cuenta y seguir añadiendo consumo.</li>
	<li><strong>Cobrar</strong>: desde la cuenta, con el botón <em>Cobrar</em> de siempre. Al
		saldarse todo, la mesa vuelve a quedar libre sola.</li>
</ol>

<p class="ayuda-nota">El importe que muestra cada mesa es lo que <strong>falta por cobrar</strong>,
no lo consumido. Si ya se cobró parte de la cuenta, la mesa sigue ocupada mostrando solo el resto.</p>

<p class="ayuda-nota">Una mesa con borde <strong>ámbar</strong> lleva mucho tiempo sin que nadie le
añada nada (el umbral se configura en <em>Configuración → POS</em>). Es un aviso para que no se
quede una cuenta olvidada sin cobrar, no un error.</p>

<p class="ayuda-nota">En la vista de <strong>plano</strong> las mesas se tocan igual que las
tarjetas: una mesa libre abre el TPV con esa mesa, una ocupada retoma su cuenta. El borde dice el
estado con los mismos colores, y dentro de cada mesa ocupada se ve lo que falta por cobrar y los
minutos que lleva abierta. En el plano <strong>no se puede mover ni cambiar nada</strong>: para eso
está <em>Editar plano</em>. Si alguna mesa de la zona no tiene sitio en la rejilla, aparece como
tarjeta bajo el plano, en «Sin sitio en el plano», para que nunca quede una mesa sin poder cobrar.</p>

<p class="ayuda-nota">Mover una cuenta a otra mesa o juntar dos cuentas se hace desde la propia
cuenta, en el chip de mesa que aparece en la cabecera del ticket.</p>

<p><strong>Editar el plano de la sala</strong> (solo con permiso de Configuración): el botón
<em>Editar plano</em> activa el lienzo de la zona seleccionada, donde cada mesa se
<strong>mueve</strong> arrastrándola por su asa (el círculo con la flecha) y se
<strong>agranda o encoge</strong> arrastrando cualquiera de sus bordes o esquinas. La mesa crece de
celda en celda: una mesa grande ocupa varias celdas de la rejilla y dibuja más sillas alrededor.
Tocar una mesa (sin arrastrarla) abre un panel para cambiar su forma (redonda, cuadrada,
barra). No hay una forma «rectangular»: una mesa rectangular es sencillamente una cuadrada
estirada. Nada se guarda hasta pulsar <em>Guardar plano</em>: recargar la página o salir
del modo edición sin guardar descarta los cambios pendientes.</p>

<p class="ayuda-nota">Al agrandar, el borde <strong>se detiene solo</strong> cuando choca con otra
mesa o con el límite de la zona: la mesa parpadea un instante y no avanza más en esa dirección,
pero puede seguir creciendo hacia donde sí haya sitio. Dos mesas nunca se solapan.</p>

<p class="ayuda-nota">Si sueltas una mesa encima de otra, la mesa que ya estaba ahí se reubica sola
en el hueco libre más cercano donde quepa entera — nunca se pierde ni queda oculta. Si no hay
espacio suficiente para ella, el movimiento se cancela con un aviso.</p>

<p>A la derecha del lienzo, en modo edición, hay un panel para <strong>gestionar zonas y
mesas</strong> sin salir de la Sala: crear (botón «+», escribir el nombre y confirmar con el
<strong>check verde</strong> o pulsando Enter; la X o Escape descartan), renombrar (tocar el nombre,
escribir y salir del campo) y eliminar (papelera, con confirmación). Es el <strong>único sitio</strong> donde se crean y editan
zonas y mesas: <em>Configuración → POS</em> ya solo guarda los ajustes del módulo (interruptor
maestro, suplemento por zona, etc.), no el listado de sala.</p>

<p class="ayuda-nota">Cambiar de pestaña de zona ya no descarta el arrastre pendiente de la zona
anterior: cada zona conserva su propio plano sin guardar mientras dure el modo edición. Solo se
pierde si se sale de «Editar plano» sin guardar, o se recarga la página.</p>
