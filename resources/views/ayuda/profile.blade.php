<p>Esta es <strong>tu cuenta</strong>: tus datos personales, tu rol, la empresa a la que
pertenecés y desde cuándo. Es tu perfil, distinto de la configuración de la empresa. El resto de
las acciones están organizadas en pestañas debajo de tus datos.</p>

<ol>
	<li><strong>Tus datos</strong>: nombre, email, rol y estado de tu cuenta se muestran arriba
		(tu rol real, el que definen tus permisos hoy, no uno desactualizado).</li>
	<li><strong>Foto de perfil</strong>: subí una imagen (PNG, JPG o WEBP, hasta 2 MB) y guardá;
		es la que se ve en el menú lateral.</li>
	<li><strong>Cambiar contraseña</strong>: pedí tu contraseña actual + la nueva (mínimo 8
		caracteres, dos veces para confirmar). Al guardar, se cierran automáticamente tus sesiones
		activas en otros dispositivos (la sesión desde la que hacés el cambio queda abierta).</li>
	<li><strong>Editar nombre</strong>: se aplica de inmediato, sin pedir contraseña.</li>
	<li><strong>Cambiar email</strong>: pedí tu contraseña actual + el nuevo correo. Te llega un
		enlace de confirmación al correo nuevo, válido por 24 horas — hasta que lo confirmes, tu
		email actual sigue funcionando para iniciar sesión. Mientras hay una solicitud pendiente,
		podés <strong>reenviar</strong> el enlace (invalida el anterior) o <strong>cancelar</strong>
		la solicitud.</li>
	<li><strong>Actividad reciente</strong>: tus últimos 5 eventos (inicios de sesión, altas,
		modificaciones, etc.), con resultado, navegador y ubicación aproximada. Si tenés permiso de
		"Logs de actividad" ves un botón <strong>Ver más</strong> hacia el historial completo.</li>
	<li><strong>Mi puesto y fichaje</strong>: solo si estás vinculado a un perfil de empleado
		activo (control de fichaje). Muestra tu puesto, tu centro de trabajo y el estado de tu
		jornada en vivo (igual que en "Fichar"), más tus últimos fichajes. Si no tenés vínculo, o
		diste de baja ese vínculo, esta pestaña no aparece.</li>
</ol>

<p class="ayuda-nota">Tu rol y permisos los define un administrador desde <strong>Usuarios</strong>
y <strong>Roles</strong>, no se cambian desde acá.</p>
