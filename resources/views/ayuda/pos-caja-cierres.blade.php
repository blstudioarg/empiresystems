<p>El <strong>historial de cierres</strong> reúne todos los cierres de caja: quién abrió y quién
cerró, cuánto se facturó y si el efectivo cuadró.</p>

<ol>
	<li><strong>Resumen del mes</strong>: arriba ves cuántos cierres hubo, lo facturado y la
		diferencia acumulada de efectivo.</li>
	<li><strong>Diferencia</strong>: <em>Cuadra</em>, <em>Sobrante</em> o <em>Faltante</em>, con el
		importe. Si se explicó una diferencia al cerrar, la observación figura en el informe.</li>
	<li><strong>Ver informe</strong>: desde Acciones reabrís el informe Z en 80 mm o A4 para
		reimprimirlo.</li>
</ol>

<p class="ayuda-nota">Los cierres no se pueden editar ni borrar: son el registro de lo que había en
el cajón cada día.</p>
