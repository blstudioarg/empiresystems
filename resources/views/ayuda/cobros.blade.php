<p>Acá ves de un vistazo cuánto te deben, quién te lo debe y qué cobraste. Las cuatro cifras de
arriba: <strong>Pendiente de cobro</strong> y <strong>Vencido</strong> son una foto de hoy (no
cambian si movés el rango de fechas); <strong>Cobrado en el periodo</strong> sí depende del rango
elegido, porque se calcula por la fecha del cobro, no de la factura.</p>

<ol>
	<li><strong>Filtros</strong>: combiná estado de cobro, cliente, serie y "Solo vencidas" para
		encontrar rápido lo que tenés que perseguir. Se aplican todos juntos.</li>
	<li><strong>Registrar cobro</strong> (menú Acciones de una fila): cargá importe, fecha, forma
		de pago y una referencia opcional. El importe se propone igual al saldo pendiente.</li>
	<li><strong>Cobros</strong> (menú Acciones): muestra el historial completo de esa factura y
		permite anular un cobro cargado por error, con confirmación previa.</li>
	<li><strong>Ver factura</strong>: abre el documento en una ventana sin perder tus filtros ni la
		página en la que estabas.</li>
</ol>

<p class="ayuda-nota">Una factura rectificada por otra no aparece con fila propia: el cobro
siempre se gestiona desde la factura original, con su importe efectivo (no el total bruto) — un
aviso en el modal lo aclara cuando corresponde.</p>
