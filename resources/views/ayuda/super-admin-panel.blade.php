<p>Este es tu <strong>panel de inicio</strong> como Super Admin: la foto de conjunto de todos los
tenants del SaaS —altas, actividad y tamaño— desde la que decidís a qué tenant entrar.</p>

<ol>
	<li><strong>Tarjetas e indicadores</strong>: total de tenants, activos, inactivos, altas de este
		mes y usuarios totales, siempre con los datos reales del momento.</li>
	<li><strong>Últimos tenants creados</strong> y <strong>ranking por tamaño</strong>: accesos
		rápidos a la gestión de tenants desde cada fila.</li>
	<li><strong>Requieren atención</strong>: tenants desactivados, sin usuarios que puedan entrar o
		sin actividad en los últimos 30 días, con el motivo indicado.</li>
	<li>Para dar de alta, editar o gestionar un tenant, entrá a <strong>Gestión de tenants</strong>
		desde el menú lateral.</li>
</ol>

<p class="ayuda-nota">Como Super Admin no tenés acceso a las pantallas de negocio de ningún tenant
(clientes, facturas, etc.): tu panel es solo este.</p>
