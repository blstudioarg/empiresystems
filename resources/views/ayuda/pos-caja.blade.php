<p>La <strong>caja</strong> controla el efectivo del día: la abrís con el fondo de cambio, vendés
normalmente desde el TPV y, al terminar, contás el cajón y la cerrás. El cierre te da el
<strong>informe Z</strong> con todo lo facturado.</p>

<ol>
	<li><strong>Abrir caja</strong>: indicá con cuánto efectivo empieza el cajón, como importe o
		contando billete a billete. Sin caja abierta no se puede cobrar (también podés abrirla desde
		el propio TPV al tocar <em>Cobrar</em>).</li>
	<li><strong>Durante el turno</strong>: ves lo vendido, los tickets y cómo te pagaron. Si sacás o
		metés efectivo que no es una venta (pago a un proveedor, retirada a la caja fuerte, cambio),
		registralo con <em>Entrada</em> o <em>Salida</em>.</li>
	<li><strong>Cerrar caja</strong>: tocá cada billete o moneda y tecleá cuántos hay (doble toque
		suma uno), o pasá a <em>Importe total</em>. Al confirmar ves lo esperado, lo contado y si
		cuadra, sobra o falta.</li>
	<li><strong>Informe Z</strong>: imprimilo en la impresora de tickets (80 mm) o en A4. Todos los
		cierres quedan en el <em>Historial</em>.</li>
</ol>

<p class="ayuda-nota">El conteo es <strong>a ciegas</strong> a propósito: no se muestra lo
esperado hasta que confirmás, para que el arqueo sea honesto. Si la diferencia es grande, te va a
pedir que escribas qué pasó. Un movimiento equivocado no se borra: registrá otro del tipo contrario
(por ejemplo, «Corrección: …»). Y un cierre no se modifica: si después se anula un ticket de ese
día, el cierre sigue mostrando lo que había en el cajón al cerrar.</p>
