<p>Desde acá exportás cualquiera de los listados principales a Excel, o importás tu cartera de
clientes, artículos o proveedores desde tu propia hoja de cálculo.</p>

<ol>
	<li><strong>Exportar</strong>: filtrá el listado como quieras (buscador, columnas) y pulsá
		"Exportar" — el archivo contiene solo lo que estás viendo en pantalla, con importes y
		fechas listos para usar en fórmulas.</li>
	<li><strong>Importar</strong>: subí tu fichero y revisá la previsualización antes de confirmar
		— ahí ves qué filas se van a crear y cuáles se rechazan, con el motivo de cada rechazo. No
		se crea nada hasta que confirmás.</li>
	<li><strong>Plantilla</strong>: descargala desde el modal de "Importar" para tener las
		columnas exactas que se esperan, con una fila de ejemplo.</li>
</ol>

<p class="ayuda-nota">Facturas y albaranes solo se pueden exportar, nunca importar — son
	documentos con numeración e impuestos que siempre se generan desde la propia aplicación.</p>
