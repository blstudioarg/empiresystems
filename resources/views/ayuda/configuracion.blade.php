<p>Acá configurás tu empresa. Está dividido en pestañas; cada una agrupa un tipo de ajuste:</p>

<ol>
	<li><strong>General</strong>: datos fiscales de tu empresa (nombre, NIF, dirección) que salen
		en las facturas.</li>
	<li><strong>Apariencia / Marca</strong>: logo, favicon y los colores de tu marca en el panel.</li>
	<li><strong>Facturación</strong>: series y numeración, cuentas bancarias y demás ajustes que
		afectan a cómo se emiten las facturas.</li>
	<li><strong>Email, Archivos, Certificado, Fichajes</strong>: envío de correos, límites de
		almacenamiento, tu certificado digital para firmar y las reglas de fichaje.</li>
	<li><strong>Asistente IA</strong>: activá el chat de ayuda pegando tu clave de API de OpenAI
		(la obtenés en platform.openai.com). Se guarda cifrada y solo se muestra enmascarada.
		Con el botón <em>Probar conexión</em> verificás que la clave funciona. El coste del uso
		corre por cuenta de tu clave.</li>
	<li><strong>Menú</strong>: renombrá el texto de cualquier sección de tu menú lateral y
		reordená arrastrando (grupos entre sí, y entradas dentro de su propio grupo). Nada se
		aplica hasta que pulsás <em>Guardar</em>. El botón <em>Restaurar valores por defecto</em>
		vuelve el menú completo (nombres y orden) al original, con confirmación previa.</li>
</ol>

<p class="ayuda-nota">En <strong>Menú</strong>, el orden y el nombre son solo de presentación: no
	cambian qué puede ver cada persona (eso lo sigue controlando su rol en Usuarios/Roles), y una
	entrada no puede arrastrarse fuera de su grupo.</p>

<p class="ayuda-nota"><strong>Privacidad del asistente:</strong> al activarlo, los mensajes de los
	usuarios y los datos que el asistente consulta (nombres de clientes, importes, etc.) se envían a
	la API de OpenAI bajo tu clave y tu responsabilidad. El asistente nunca emite facturas, cobra
	ni borra: solo consulta y propone borradores que vos confirmás.</p>

<p class="ayuda-nota">Los datos de General y el Certificado son los que usa la facturación legal:
revisalos bien antes de empezar a emitir.</p>
