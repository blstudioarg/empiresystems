<p>Las opciones son las variantes con las que se comanda un plato: punto de cocción, guarnición,
extras… Se definen una vez y se reutilizan en todos los artículos que las necesiten.</p>

<ol>
	<li><strong>Crear un grupo</strong>: un grupo agrupa opciones excluyentes o combinables (por
		ejemplo «Punto de cocción»). Ahí se decide si es obligatorio y cuántas opciones se pueden
		elegir como mínimo y como máximo.</li>
	<li><strong>Crear las opciones</strong> dentro del grupo, con su precio por defecto.</li>
	<li><strong>Asignarlas a los artículos</strong> desde el catálogo: en cada artículo se eligen
		los grupos que le aplican y el precio que tiene cada opción <em>en ese artículo</em>.</li>
</ol>

<p class="ayuda-nota">El precio de una opción es <strong>propio de cada artículo</strong>: «Extra
queso» puede costar 1,50 € en el solomillo y 0,50 € en el bocadillo. Cambiar el precio por defecto
de la opción no altera los precios ya asignados en los artículos.</p>

<p class="ayuda-nota">Un grupo <strong>obligatorio</strong> no puede quedarse sin opciones: si no,
el artículo no se podría comandar. El sistema lo impide al guardar.</p>

<p class="ayuda-nota">Si una opción tiene un <strong>artículo vinculado</strong>, al venderla se
descuenta el stock de ese artículo, pero <strong>no</strong> aparece como línea aparte en el
ticket: se muestra como detalle bajo el plato.</p>

<p class="ayuda-nota">No se puede eliminar un grupo o una opción que esté en uso: el sistema avisa
en cuántos artículos aparece.</p>
